"""Export service: generates structured Markdown and audit JSON packages."""
import json
import os
from pathlib import Path
from typing import Dict, Any
from src.config.settings import get_settings


class ExportService:
    """Handles formatting and persisting export artifacts for completed or reviewed lessons."""

    def __init__(self, exports_dir: str | None = None):
        settings = get_settings()
        self.exports_dir = Path(exports_dir or settings.exports_dir)
        self.exports_dir.mkdir(parents=True, exist_ok=True)

    def export_markdown(self, run_id: str, topic: str, lesson_content: str | None, final_status: str) -> str:
        """Format and return complete lesson as a polished Markdown document."""
        filename = f"{run_id}_lesson.md"
        filepath = self.exports_dir / filename
        
        banner = (
            f"# Lesson: {topic}\n\n"
            f"> **Quality Gate Status**: `{final_status}`  \n"
            f"> **Run ID**: `{run_id}`  \n"
            f"> **Generated By**: LessonForge AI Self-Evaluating Engine  \n\n"
            f"---\n\n"
        )
        content_str = lesson_content or "(No lesson content generated)"
        full_content = banner + content_str
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(full_content)
        return str(filepath)

    def export_json_report(
        self,
        run_data: Dict[str, Any],
        lesson_versions: list[Dict[str, Any]],
        evaluations: list[Dict[str, Any]],
        rejections: list[Dict[str, Any]]
    ) -> str:
        """Create a full audit trail JSON report containing all run metadata, versions, and evaluations."""
        run_id = run_data.get("run_id", "unknown_run")
        filename = f"{run_id}_audit_report.json"
        filepath = self.exports_dir / filename

        report_payload = {
            "run_metadata": run_data,
            "version_count": len(lesson_versions),
            "versions": lesson_versions,
            "evaluations": evaluations,
            "rejections": rejections
        }

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(report_payload, f, indent=2, default=str)
        return str(filepath)
